#!/usr/bin/env python3
"""What the room looks like, as numbers, for the cache of traced rooms.

    room-key.py out.h room.glsl gpu.c

A traced room is kept on disk from one login to the next, and is traced
again only when it would come out different. Every change to the scene has
to reach the shader -- room.glsl is the C tracer's double, and checked
against it -- so a hash of the shader stands for the room; a change on the
C side alone (a camera, the resolve, the sidecar) bumps ROOM_LOOK in
draw.c. Whether this machine's GPU traces it right is asked again when
gpu.c changes as well. Run by meson with the Python meson itself runs on.
"""

import sys


def fnv(data, h=2166136261):
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def main():
    out, glsl, gpu = sys.argv[1:4]
    with open(glsl, "rb") as f:
        room = fnv(f.read())
    with open(gpu, "rb") as f:
        both = fnv(f.read(), room)
    with open(out, "w", encoding="ascii") as f:
        f.write("/* generated by room-key.py: a hash of room.glsl, and of gpu.c after it */\n")
        f.write("#define DESK_ROOM_GLSL_KEY 0x%08xu\n" % room)
        f.write("#define DESK_ROOM_GPU_KEY 0x%08xu\n" % both)


if __name__ == "__main__":
    main()
